// Writes js/worldmap/engineGroundData.js: the game map's ground over the regional layer's cells (engineGround.js),
// so the engine need not make the map's ground (~6 s) in every process. Run after any change to the world map's
// ground (WorldMapGenerator: its regions' relief, the divide, erosion, valleys); tests/engine-ground.mjs fails until then.
//   node scripts/build-engine-ground.mjs
import { writeFileSync } from 'node:fs';
import { computeEngineGroundReliefM, WORLD_MAP_SEED } from '../js/worldmap/engineGround.js';
import { REGIONAL_DEFAULTS } from '../js/atmosphere/RegionalAtmosphere.js';

const relief = computeEngineGroundReliefM(REGIONAL_DEFAULTS, {});
const rows = [];
for (let y = 0; y < REGIONAL_DEFAULTS.rows; y++) rows.push(Array.from(relief.slice(y * REGIONAL_DEFAULTS.columns, (y + 1) * REGIONAL_DEFAULTS.columns), v => v.toFixed(2)).join(','));
writeFileSync(new URL('../js/worldmap/engineGroundData.js', import.meta.url), `// Generated by scripts/build-engine-ground.mjs from the world map of seed ${WORLD_MAP_SEED}; do not edit.
// The ground's departure from the regional layer's slope (m) at each of its ${REGIONAL_DEFAULTS.columns} x ${REGIONAL_DEFAULTS.rows} cells, rows from the north.
export const ENGINE_GROUND = Object.freeze({ seed: ${WORLD_MAP_SEED}, columns: ${REGIONAL_DEFAULTS.columns}, rows: ${REGIONAL_DEFAULTS.rows}, cellKm: ${REGIONAL_DEFAULTS.cellKm}, reliefM: [
${rows.join(',\n')}
] });
`);
console.log('wrote js/worldmap/engineGroundData.js');
