// Writes the products' colours (js/forecast/productColours.js) into the Roblox place, so the
// game and the web developer views share one source: roblox/src/shared/Weather/Palettes.luau.
// Radar colour tables come from js/radar/RadarFormat.js (radarColorTable, as the web radar draws them).
// Run after changing a colour: node scripts/export-palettes.mjs
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { CATEGORY_COLOURS, CATEGORY_SHORT, CHANCE_COLOURS, WATCH_COLOURS, DISCUSSION_COLOURS, WARNING_COLOURS } from '../js/forecast/productColours.js';
import { RADAR_PRODUCTS, radarColorTable, RANGE_FOLDED } from '../js/radar/RadarFormat.js';

// The radar products the game shows (server/GameProducts.js): a single site's lowest tilt, and the mosaics.
const RADAR_SHOWN = ['reflectivity', 'velocity', 'stormRelativeVelocity', 'echoTops', 'vil', 'mesh'];

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'roblox/src/shared/Weather/Palettes.luau');

const rgb = hex => `{ ${[1, 3, 5].map(k => parseInt(hex.slice(k, k + 2), 16)).join(', ')} }`;
const table = (entries, key = k => k, indent = '\t') => `{\n${entries.map(([k, v]) => `${indent}\t${key(k)} = ${v},`).join('\n')}\n${indent}}`;

// One radar product as a Luau table entry.
const radarEntry = key => {
  const spec = RADAR_PRODUCTS[key];
  return [
    `\t${key} = {`,
    `\t\tlabel = "${spec.label}", short = "${spec.short}", units = "${spec.units}", min = ${spec.min}, step = ${spec.step}, decimals = ${spec.decimals},`,
    `\t\tdoppler = ${Boolean(spec.doppler)}, legend = { ${spec.legend.join(', ')} },`,
    `\t\tlut = { ${Array.from(radarColorTable(key)).join(', ')} },`,
    '\t},'
  ].join('\n');
};

const text = `--!strict
-- Generated by scripts/export-palettes.mjs from js/forecast/productColours.js and
-- js/radar/RadarFormat.js; do not edit here.
-- Colours are { r, g, b } in 0-255, for drawing straight into image buffers.

local Palettes = {}

-- Outlook categories, lowest first, and their short labels.
Palettes.CATEGORY = ${table(Object.entries(CATEGORY_COLOURS).map(([k, v]) => [k, rgb(v)]), k => k, '')}
Palettes.CATEGORY_SHORT = ${table(Object.entries(CATEGORY_SHORT).map(([k, v]) => [k, `"${v}"`]), k => k, '')}

-- Each hazard's chance contours, by level (percent).
Palettes.CHANCE = {
${Object.entries(CHANCE_COLOURS).map(([hazard, levels]) => `\t${hazard} = ${table(Object.entries(levels).map(([k, v]) => [k, rgb(v)]), k => `[${k}]`, '\t')},`).join('\n')}
}

-- Watches, mesoscale discussions and warnings, by the colour key the weather server gives each.
Palettes.WATCH = ${table(Object.entries(WATCH_COLOURS).map(([k, v]) => [k, rgb(v)]), k => k, '')}
Palettes.DISCUSSION = ${table(Object.entries(DISCUSSION_COLOURS).map(([k, v]) => [k, rgb(v)]), k => k, '')}
Palettes.WARNING = ${table(Object.entries(WARNING_COLOURS).map(([k, v]) => [k, rgb(v)]), k => k, '')}

-- Radar products: how a byte reads (value = min + (byte - 1) * step; 0 is no echo, and in the
-- Doppler products ${RANGE_FOLDED} is range folded) and its colour: lut[byte * 4 + 1 .. 4] = r, g, b, a.
Palettes.RADAR = {
${RADAR_SHOWN.map(radarEntry).join('\n')}
}

return Palettes
`;
writeFileSync(OUT, text);
console.log(`wrote ${path.relative(ROOT, OUT)}`);
