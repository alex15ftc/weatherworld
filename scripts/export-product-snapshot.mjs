// Records the game products from a running weather server into the Roblox place, so the
// product screens work in Studio with no server: roblox/src/worlddata/ProductSnapshot.
//   Meta.luau   { recordedAt, simHourUtc, epoch, products = { [id] = { version, module } } }
//   P001.luau   ... each returns one product's JSON text, as a list of parts (joined in order).
// The place uses it when no feed URL is set (server/ProductFeed.luau).
//
//   node scripts/export-product-snapshot.mjs [--from http://localhost:3000] [--key <WEATHER_GAME_KEY>] [--no-sites]
// Every radar's scans are included unless --no-sites (about 50 KB a product, 3 products a radar).
import { mkdirSync, writeFileSync, rmSync, existsSync, readdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'roblox/src/worlddata/ProductSnapshot');
const arg = name => { const k = process.argv.indexOf(name); return k > 0 ? process.argv[k + 1] : undefined; };
const FROM = (arg('--from') ?? 'http://localhost:3000').replace(/\/+$/, '');
const KEY = arg('--key') ?? process.env.WEATHER_GAME_KEY;
// A module's source is kept well under what Studio and Rojo handle comfortably.
const PART_CHARS = 150_000;

async function get(route) {
  const response = await fetch(`${FROM}${route}`, { headers: KEY ? { 'x-api-key': KEY } : {} });
  if (!response.ok) throw new Error(`${route}: HTTP ${response.status}`);
  return response.text();
}

// A Luau long string that the text cannot close early.
function longString(text) {
  let level = 1;
  while (text.includes(`]${'='.repeat(level)}]`)) level++;
  const eq = '='.repeat(level);
  return `[${eq}[${text}]${eq}]`;
}

const manifest = JSON.parse(await get('/api/game/v1/manifest'));
// Each radar's lowest tilt is made only when asked for, so it is asked for here (--no-sites leaves them out).
if (!process.argv.includes('--no-sites') && manifest.products['radar.sites']) {
  const sites = JSON.parse(await get('/api/game/v1/product/radar.sites'));
  for (const site of sites.sites) for (const product of sites.siteProducts) await get(`/api/game/v1/product/radar.site.${site.id}.${product}`);
  Object.assign(manifest.products, JSON.parse(await get('/api/game/v1/manifest')).products);
}
mkdirSync(OUT, { recursive: true });
if (existsSync(OUT)) for (const name of readdirSync(OUT)) if (/^P\d+\.luau$|^Meta\.luau$/.test(name)) rmSync(path.join(OUT, name));

const entries = [];
let n = 0;
for (const id of Object.keys(manifest.products)) {
  const text = await get(`/api/game/v1/product/${id}`);
  const module = `P${String(++n).padStart(3, '0')}`;
  const parts = [];
  for (let k = 0; k < text.length; k += PART_CHARS) parts.push(longString(text.slice(k, k + PART_CHARS)));
  writeFileSync(path.join(OUT, `${module}.luau`), `-- Generated by scripts/export-product-snapshot.mjs (${id})\nreturn {\n${parts.join(',\n')},\n}\n`);
  const status = JSON.parse(text).status ?? '';
  entries.push(`\t\t["${id}"] = { version = "${manifest.products[id].version}", module = "${module}" },`);
  console.log(`${id}: ${status} ${(text.length / 1024).toFixed(1)} KB -> ${module}`);
}
writeFileSync(path.join(OUT, 'Meta.luau'), `-- Generated by scripts/export-product-snapshot.mjs
return {
	recordedAt = "${new Date().toISOString()}",
	simHourUtc = ${manifest.simHourUtc ?? 'nil'},
	epoch = ${manifest.epoch},
	products = {
${entries.join('\n')}
	},
}
`);
console.log(`wrote ${n} products to ${path.relative(ROOT, OUT)}`);
