import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const input = path.resolve(valueAfter('--input') || 'training-cache/processed/noaa-cases.json');
const auditOutput = path.resolve(valueAfter('--audit-output') || 'data/analogs/noaa-historical-analog-catalog.json');
const moduleOutput = path.resolve(valueAfter('--module-output') || 'js/analogs/generatedNoaaHistoricalAnalogCatalog.js');
const atmosphereInput = path.resolve(valueAfter('--atmosphere-input') || 'training-cache/processed/noaa-atmospheres.json');
const atmosphereModuleOutput = path.resolve(valueAfter('--atmosphere-module-output') || 'js/analogs/generatedNoaaAtmosphereCatalog.js');
const records = JSON.parse(await readFile(input, 'utf8'));
const atmospheres = JSON.parse(await readFile(atmosphereInput, 'utf8'));
if (!Array.isArray(records)) throw new Error('NOAA processed corpus must be a JSON array');

const valid = records.map(validateRecord).sort((a,b) => a.eventDate.localeCompare(b.eventDate));
if (valid.length < 25) throw new Error(`At least 25 complete NOAA cases are required; received ${valid.length}`);
const ids = new Set(valid.map(record => record.analogId));
if (ids.size !== valid.length) throw new Error('NOAA corpus contains duplicate analog IDs');
const validAtmospheres = atmospheres.map(validateAtmosphere).sort((a,b)=>a.eventDate.localeCompare(b.eventDate));
const atmosphereDates = new Set(validAtmospheres.map(item=>item.eventDate));
if (atmosphereDates.size !== validAtmospheres.length) throw new Error('NOAA atmosphere corpus contains duplicate dates');
for (const record of valid) if (!atmosphereDates.has(record.eventDate)) {
  throw new Error(`Missing full-atmosphere sequence for ${record.eventDate}`);
}

await mkdir(path.dirname(auditOutput), { recursive:true });
await mkdir(path.dirname(moduleOutput), { recursive:true });
await mkdir(path.dirname(atmosphereModuleOutput), { recursive:true });
await writeFile(auditOutput, JSON.stringify(valid, null, 2));
await writeFile(moduleOutput,
  `// Generated by scripts/build-noaa-analog-catalog.mjs. Do not edit manually.\n`
  + `export const NOAA_HISTORICAL_ANALOG_CATALOG = Object.freeze(${JSON.stringify(valid)});\n`
);
await writeFile(atmosphereModuleOutput,
  `// Generated by scripts/build-noaa-analog-catalog.mjs. Do not edit manually.\n`
  + `export const NOAA_ATMOSPHERE_CATALOG = Object.freeze(${JSON.stringify(validAtmospheres)});\n`
);
console.log(JSON.stringify({
  records:valid.length,
  firstDate:valid[0].eventDate,
  lastDate:valid.at(-1).eventDate,
  uniqueDates:new Set(valid.map(record => record.eventDate)).size,
  atmosphereSequences:validAtmospheres.length,
  providers:['NOAA NCEI NARR','NOAA NCEI IGRA 2','NOAA NCEI Storm Events'],
  auditOutput,moduleOutput,atmosphereModuleOutput
}, null, 2));

function validateRecord(record, index) {
  const label = `record ${index}`;
  if (!/^\d{4}-\d{2}-\d{2}$/.test(record?.eventDate ?? '')) throw new Error(`${label}: invalid eventDate`);
  if (record.provenance?.environment !== 'NOAA NCEI NARR') throw new Error(`${label}: NARR provenance required`);
  if (record.provenance?.soundings !== 'NOAA NCEI IGRA 2 / NARR hybrid') throw new Error(`${label}: IGRA/NARR provenance required`);
  if (record.provenance?.reports !== 'NOAA Storm Events candidate-day screening') throw new Error(`${label}: Storm Events screening provenance required`);
  if (!Array.isArray(record.soundingSequence) || record.soundingSequence.length !== 3) throw new Error(`${label}: 12Z/18Z/00Z sounding sequence required`);
  const hours = record.soundingSequence.map(item => item.hourUtc);
  if (hours.join(',') !== '12,18,24') throw new Error(`${label}: sounding hours must be 12,18,24`);
  for (const sounding of record.soundingSequence) {
    if (!Array.isArray(sounding.levels) || sounding.levels.length < 5) throw new Error(`${label}: sounding needs at least five levels`);
    for (const level of sounding.levels) for (const key of ['pressureHpa','temperatureC','dewpointC','windDirection','windSpeedKt']) {
      if (!Number.isFinite(Number(level[key]))) throw new Error(`${label}: non-finite ${key}`);
    }
  }
  for (const key of ['family','environment','diagnostics']) if (!record.pattern?.[key]) throw new Error(`${label}: missing pattern.${key}`);
  return record;
}
function validateAtmosphere(item, index) {
  const label=`atmosphere ${index}`;
  if (!/^\d{4}-\d{2}-\d{2}$/.test(item?.eventDate??'')) throw new Error(`${label}: invalid eventDate`);
  if (!Array.isArray(item.sequence)||item.sequence.map(frame=>frame.hourUtc).join(',')!=='12,18,24,30,36') {
    throw new Error(`${label}: 12Z/18Z/00Z/06Z/12Z sequence required`);
  }
  for (const frame of item.sequence) {
    const size=Number(frame.width)*Number(frame.height);
    for (const [name,values] of Object.entries(frame.fields??{})) {
      if (!Array.isArray(values)||values.length!==size||values.some(value=>!Number.isFinite(Number(value)))) {
        throw new Error(`${label}: invalid ${name} grid`);
      }
    }
  }
  return item;
}
function valueAfter(flag) {
  const index = process.argv.indexOf(flag);
  return index >= 0 ? process.argv[index + 1] : null;
}
