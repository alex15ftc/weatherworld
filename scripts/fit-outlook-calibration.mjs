// Fits js/forecast/outlookCalibrationTable.js from outlook-audit JSON (scripts/outlook-audit.mjs
// with OUTLOOK_AUDIT_JSON set). Two stages, each from its own run:
//   1. Tiers: from a run with OUTLOOK_CALIBRATION=off. Each published tier maps to the highest
//      tier not exceeding its observed frequency; tiers with too few samples are left
//      unmapped; mappings are monotonic and never drop a tier whose events occur at least
//      half as often as the lowest published level. Replaces the table (categories dropped).
//        node scripts/fit-outlook-calibration.mjs raw.json
//   2. Categories: from a run with tier calibration on and OUTLOOK_CATEGORY_CALIBRATION=off.
//      Each issued overall category maps to the median practically-perfect observed category
//      of its products (monotonic, at most two tiers down or one up, never below MRGN).
//      Keeps the fitted tiers.
//        node scripts/fit-outlook-calibration.mjs --categories tiered.json
import fs from 'node:fs';

const TABLE_PATH = 'js/forecast/outlookCalibrationTable.js';
const categoriesMode = process.argv[2] === '--categories';
const input = JSON.parse(fs.readFileSync(process.argv[categoriesMode ? 3 : 2], 'utf8'));

function writeTable(table) {
  fs.writeFileSync(TABLE_PATH, `// Generated by scripts/fit-outlook-calibration.mjs from outlook-audit runs (tiers: calibration\n// off; categories: tiers on, categories off). Maps published tier -> verified tier per day and\n// hazard, and issued category -> verified category per day. Do not hand-edit.\nexport const OUTLOOK_CALIBRATION_TABLE = ${JSON.stringify(table, null, 2)};\n`);
}

if (categoriesMode) {
  if (input.calibration === 'off' || input.categoryCalibration !== 'off') console.warn('warning: fit categories from a run with tier calibration on and OUTLOOK_CATEGORY_CALIBRATION=off');
  const { OUTLOOK_CALIBRATION_TABLE: table } = await import(`../${TABLE_PATH}?t=${Date.now()}`);
  const RISKS = ['TSTM', 'MRGN', 'SLGT', 'ENH', 'MDT', 'HIGH'];
  const MIN_PRODUCTS = 4;
  const categories = {};
  for (const [day, byForecast] of Object.entries(input.categories ?? {})) {
    const map = {};
    let floor = 1;
    for (const risk of RISKS.slice(1)) {
      const observed = byForecast[risk];
      if (!observed || observed.length < MIN_PRODUCTS) continue;
      const ranks = observed.map(r => RISKS.indexOf(r)).sort((a, b) => a - b);
      const median = ranks[Math.floor((ranks.length - 1) / 2)];
      const index = RISKS.indexOf(risk);
      const target = Math.max(floor, 1, index - 2, Math.min(index + 1, median));
      floor = target;
      if (target !== index) map[risk] = RISKS[target];
      console.log(`${day} ${risk}: n=${observed.length} median observed ${RISKS[median]} -> ${RISKS[target]}`);
    }
    if (Object.keys(map).length) categories[day] = map;
  }
  writeTable({ ...table, categoriesFittedFrom: { seeds: input.seeds, hours: input.hours, minProductsPerCategory: MIN_PRODUCTS }, categories });
  console.log(JSON.stringify(categories, null, 1));
} else {
  if (input.calibration !== 'off') console.warn('warning: reliability was measured with calibration enabled; refit from a raw (OUTLOOK_CALIBRATION=off) run');
  const LEVELS = { tornado: [2, 5, 10, 15, 30, 45, 60], hail: [5, 15, 30, 45, 60, 75, 90], wind: [5, 15, 30, 45, 60, 75, 90] };
  const MIN_CELLS = 300;
  const tiers = {};
  for (const [day, hazards] of Object.entries(input.reliability)) {
    for (const [hazard, buckets] of Object.entries(hazards)) {
      const map = {};
      let floor = 0;
      for (const level of LEVELS[hazard]) {
        const b = buckets[level];
        if (!b || b.cells < MIN_CELLS) continue;
        const observedPct = 100 * b.hits / b.cells;
        let target = [...LEVELS[hazard]].reverse().find(l => l <= observedPct) ?? 0;
        if (target === 0 && observedPct >= LEVELS[hazard][0] / 2) target = LEVELS[hazard][0];
        target = Math.max(target, floor); // monotonic
        floor = target;
        map[level] = target;
      }
      if (Object.keys(map).length) (tiers[day] ??= {})[hazard] = map;
    }
  }
  writeTable({ version: `fitted-${new Date().toISOString().slice(0, 10)}`, fittedFrom: { seeds: input.seeds, hours: input.hours, minCellsPerTier: MIN_CELLS }, tiers });
  console.log(JSON.stringify(tiers, null, 1));
}
